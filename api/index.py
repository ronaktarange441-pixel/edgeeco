"""
EcoEdge Autonomous Agent - Hackathon Prototype
===============================================
A simulated Edge-IoT smart factory controller. Live telemetry (temperature,
vibration) is generated by a background simulator. A Google Gemini agent
analyzes each reading and issues machine commands (NONE / THROTTLE /
EMERGENCY_SHUTDOWN) as strict JSON. A deterministic rule engine acts as an
offline fallback so the system always makes a decision, even without network.

Security: the Gemini key is loaded server-side from .env and is never exposed
in any API response or static asset.
"""

import json
import logging
import os
import random
import threading
import time
from collections import deque
from pathlib import Path

from dotenv import load_dotenv
from fastapi import FastAPI
from fastapi.staticfiles import StaticFiles
from google import genai
from google.genai import types

log = logging.getLogger("ecoedge")
logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")

# --------------------------------------------------------------------------
# Config & secrets
# --------------------------------------------------------------------------
load_dotenv()
GEMINI_API_KEY = os.getenv("GEMINI_API_KEY", "")
if not GEMINI_API_KEY:
    raise SystemExit("FATAL: GEMINI_API_KEY not found in .env - refusing to start.")

PUBLIC_DIR = Path(__file__).resolve().parent.parent / "public"
MACHINE = "PNEUMATIC_PRESS_03"

SYSTEM_PROMPT = """You are an Industrial Safety Agent for a smart factory edge controller.
You receive live IoT sensor telemetry from one machine. Analyse the reading and decide
the machine's safety state and the action to take.

Safety rules (they are YOUR knowledge of machine-health limits):
- Temperature below 85 degC is NORMAL.
- Temperature 85-94 degC is HIGH (warn / throttle the machine).
- Temperature 95+ degC is CRITICAL (emergency shutdown).
- Vibration below 6.0 mm/s is NORMAL.
- Vibration 6.0-9.9 mm/s is HIGH (warn / throttle the machine).
- Vibration 10.0+ mm/s is CRITICAL (emergency shutdown).

Respond with ONLY a single valid JSON object, no markdown fences, no commentary:
{"status": "SAFE"|"CRITICAL", "action": "NONE"|"THROTTLE"|"EMERGENCY_SHUTDOWN", "reason": "short human-readable reason or NONE"}
- SAFE + NONE when every reading is normal.
- CRITICAL + THROTTLE when a HIGH threshold is exceeded.
- CRITICAL + EMERGENCY_SHUTDOWN when a CRITICAL threshold is exceeded."""

# --------------------------------------------------------------------------
# AI client setup (raises only if the SDK itself is broken, never on network)
# The timeout is in milliseconds and caps every call so the simulator thread
# can never hang forever on a wedged network request.
# --------------------------------------------------------------------------
GEMINI_MODEL = "gemini-3.8-flash"
GEMINI_TIMEOUT_MS = 15_000
CLIENT = genai.Client(
    api_key=GEMINI_API_KEY,
    http_options=types.HttpOptions(timeout=GEMINI_TIMEOUT_MS),
)

# --------------------------------------------------------------------------
# Shared in-memory state
# --------------------------------------------------------------------------
LOCK = threading.Lock()
STATE = {
    "sensor": {
        "machine": MACHINE,
        "temperature": 68.0,
        "vibration": 2.0,
        "timestamp": "-",
    },
    "agent": {
        "status": "SAFE",
        "action": "NONE",
        "reason": "Waiting for first AI evaluation...",
        "source": "gemini",
        "latency_ms": 0,
        "last_eval": "-",
        "model": "gemini-3.8-flash",
    },
    "log": deque(maxlen=8),
    "uptime_s": 0.0,
}
START_TIME = time.time()
# --------------------------------------------------------------------------
# Lightweight rule fallback: same safety limits as the Gemini system prompt.
# Guarantees a decision even when the API key is not live / network down.
# --------------------------------------------------------------------------

def rule_fallback(temp: float, vib: float):
    if temp >= 95.0 or vib >= 10.0:
        return "CRITICAL", "EMERGENCY_SHUTDOWN"
    if temp >= 85.0 or vib >= 6.0:
        return "CRITICAL", "THROTTLE"
    return "SAFE", "NONE"


def ask_gemini(payload: dict) -> dict:
    """Call Gemini, parse strictly, and fall back to rule engine if the reply
    is malformed, incomplete, or the API is unreachable."""
    prompt = (
        f"Machine: {payload['machine']}\n"
        f"Temperature: {payload['temperature']} degC\n"
        f"Vibration: {payload['vibration']} mm/s\n"
        "Respond with JSON only."
    )
    started = time.time()
    source = "gemini"
    try:
        response = CLIENT.models.generate_content(
            model=GEMINI_MODEL,
            contents=prompt,
            config=types.GenerateContentConfig(
                system_instruction=SYSTEM_PROMPT,
                temperature=0.0,
                response_mime_type="application/json",
            ),
        )
        raw = (response.text or "").strip()
        raw = raw.removeprefix("```json").removeprefix("```").removesuffix("```").strip()
        parsed = json.loads(raw)
        decision = {
            "status": str(parsed.get("status", "")).upper(),
            "action": str(parsed.get("action", "")).upper(),
            "reason": str(parsed.get("reason", "NONE")),
        }
        if decision["action"] not in {"NONE", "THROTTLE", "EMERGENCY_SHUTDOWN"}:
            raise ValueError("unknown action")
    except Exception as exc:  # noqa: BLE001 - any failure degrades to rules
        log.warning("Gemini evaluation failed (%s), using rule engine", repr(exc))
        status, action = rule_fallback(payload["temperature"], payload["vibration"])
        decision = {"status": status, "action": action,
                    "reason": "AI unavailable (fallback: %s)" % type(exc).__name__}
        source = "rules"
    decision["latency_ms"] = int((time.time() - started) * 1000)
    decision["source"] = source
    return decision


# --------------------------------------------------------------------------
# Simulation background loop: random walk + rare dangerous spikes
# --------------------------------------------------------------------------

def simulation_loop():
    temp, vib = 68.0, 2.0
    cycle = 0
    while True:
        spike = random.random() < 0.06
        temp = max(20.0, min(110.0, temp + random.uniform(-1.5, 1.5)
                             + (random.uniform(8, 18) if spike else 0)))
        vib = max(0.5, min(16.0, vib + random.uniform(-0.3, 0.3)
                           + (random.uniform(3, 9) if spike else 0)))
        payload = {
            "machine": MACHINE,
            "temperature": round(temp, 1),
            "vibration": round(vib, 2),
        }
        decision = ask_gemini(payload)

        with LOCK:
            STATE["sensor"].update(
                temperature=payload["temperature"],
                vibration=payload["vibration"],
                timestamp=time.strftime("%H:%M:%S"),
            )
            STATE["agent"].update(
                status=decision.get("status", "SAFE"),
                action=decision.get("action", "NONE"),
                reason=decision.get("reason") or "NONE",
                source=decision.get("source", "gemini"),
                latency_ms=decision.get("latency_ms", 0),
                last_eval=time.strftime("%H:%M:%S"),
            )
            STATE["log"].appendleft({
                "t": time.strftime("%H:%M:%S"),
                "temp": payload["temperature"],
                "vib": payload["vibration"],
                "action": decision.get("action", "NONE"),
            })
            STATE["uptime_s"] = round(time.time() - START_TIME, 1)

        if decision.get("action") != "NONE" or cycle % 10 == 0:
            log.info("t=%.1f v=%.2f -> %s/%s (%s, %dms)",
                     payload["temperature"], payload["vibration"],
                     decision.get("status"), decision.get("action"),
                     decision.get("source"), decision.get("latency_ms", 0))
        cycle += 1
        time.sleep(2)


# --------------------------------------------------------------------------
# FastAPI app
# --------------------------------------------------------------------------
app = FastAPI(title="EcoEdge Autonomous Agent")


@app.get("/api/state")
def api_state() -> dict:
    """Latest sensor reading + the agent's current decision (never exposes keys)."""
    with LOCK:
        return {
            "sensor": dict(STATE["sensor"]),
            "agent": dict(STATE["agent"]),
            "log": list(STATE["log"]),
            "uptime_s": STATE["uptime_s"],
        }


# Mount the static dashboard LAST so /api routes are matched first.
app.mount("/", StaticFiles(directory=PUBLIC_DIR, html=True), name="public")


@app.on_event("startup")
def startup() -> None:
    threading.Thread(target=simulation_loop, daemon=True, name="iot-sim").start()
    log.info("EcoEdge agent online. Dashboard: http://127.0.0.1:8000")